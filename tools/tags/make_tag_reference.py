# Written by Claude (claude-opus-5-5), 2026-11-22: builds docs/tags/TAGS.md, the list of every declared tag with its description, its
# redirects (old names) and deprecations, from the tag declarations files (tag spec 6). Tags are hard to change once saved files use
# them, so the reference is what designers read before adding or picking one.
#
# Run from the project folder (it only reads the declarations):
#   python tools/tags/make_tag_reference.py
import json
import pathlib
import re
import sys

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
from apply_redirects import ROOT, declaration_files, read_redirects  # noqa: E402

OUT = ROOT / "docs/tags/TAGS.md"
ENTRY = re.compile(r'&("(?:[^"\\]|\\.)*")\s*:\s*("(?:[^"\\]|\\.)*")')


def read(files):
    tags, deprecated = {}, set()
    for path in files:
        for line in path.read_text(encoding="utf-8").splitlines():
            if line.startswith("tags = "):
                for name, text in ENTRY.findall(line):
                    tags[json.loads(name)] = json.loads(text)
            elif line.startswith("deprecated = "):
                deprecated.update(re.findall(r'&"([^"]+)"', line))
    return tags, deprecated


def main():
    files = declaration_files()
    tags, deprecated = read(files)
    redirects = read_redirects(files)
    old_names = {}
    for old, new in redirects.items():
        old_names.setdefault(new, []).append(old)
    lines = [
        "<!-- Generated by tools/tags/make_tag_reference.py from the tag declarations; don't edit by hand. -->",
        "",
        "# Tags",
        "",
        "Every declared tag, by category, with what it is. A tag's first level is its category; a tag covers the tags under it. "
        "How tags work, how to add one and how to rename one: [the tags README](../../assets/scripts/tags/README.md). "
        "The design: [TAG_SPEC.md](TAG_SPEC.md).",
        "",
        "Declared in: " + ", ".join("`%s`" % f.relative_to(ROOT).as_posix() for f in files) + ".",
        "",
    ]
    categories = sorted({t.split(".")[0] for t in tags})
    for category in categories:
        lines += ["## `%s`" % category, "", tags.get(category, "*(no description)*"), ""]
        lines += ["| Tag | What it is | Old names |", "|---|---|---|"]
        for tag in sorted(t for t in tags if t.split(".")[0] == category and t != category):
            depth = tag.count(".") - 1
            name = "&nbsp;" * 4 * depth + "`%s`" % tag
            text = tags[tag] or "*(no description)*"
            if tag in deprecated:
                text = "**Deprecated.** " + text
            lines.append("| %s | %s | %s |" % (name, text, ", ".join("`%s`" % o for o in sorted(old_names.get(tag, [])))))
        lines.append("")
    undescribed = [t for t, text in tags.items() if not text]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("Wrote %s: %d tags in %d categories, %d redirects%s." % (OUT.relative_to(ROOT).as_posix(), len(tags), len(categories),
          len(redirects), "; no description: " + ", ".join(undescribed) if undescribed else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
