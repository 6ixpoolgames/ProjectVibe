# Written by Claude (claude-opus-5-5), 2026-11-17: builds each system's REFERENCE.md, the class-by-class, function-by-function
# reference, from the ## doc comments in its scripts (the owner's call: the comments are the reference, so the two can't drift apart).
#
# How it works: Godot's own doc tool (--doctool --gdscript-docs) reads every script under assets/scripts and writes one XML file per
# class, the same data the editor's built-in help shows. This turns those into Markdown, one REFERENCE.md per system folder
# (assets/scripts/<system>/REFERENCE.md), with production scripts only: tests/, debug/ and samples/ are left out.
#
# Run from the project folder, with the Godot editor closed or open (it only reads):
#   python tools/docs/make_reference.py               every system
#   python tools/docs/make_reference.py navigation    only these systems
# Godot is looked for beside the project folder, as tools/run_tests.sh does; set GODOT to use another.
#
# Writing doc comments that read well here and in the editor's help (Godot's doc comment markup):
#   - The first ## paragraph is the brief description; a ## line on its own starts the longer description.
#   - Lines run together into one paragraph, blank ## lines too. A "## [br]" line between paragraphs breaks them, and "[br]- "
#     starts each item of a list on its own line.
#   - [code]text[/code] for code in a sentence, [codeblock] ... [/codeblock] for examples, [b]bold[/b].
#   - [ClassName] links to that class: in this project, its entry in its system's REFERENCE.md; an engine class, Godot's docs.
#     [method name], [member name], [signal name] and [constant NAME] name things in the same class.
#   - The "Written by Claude" header is a plain # comment, so it stays out of the reference.
import os
import re
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ElementTree

PROJECT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCRIPTS = os.path.join(PROJECT, "assets", "scripts")
GODOT = os.environ.get("GODOT", os.path.join(PROJECT, "..", "Godot_v4.7.2-stable_win64_console.exe"))
# Folders that never hold production code.
NOT_PRODUCTION = {"tests", "debug", "samples"}
GODOT_DOCS = "https://docs.godotengine.org/en/stable/classes/class_%s.html"
# Every class_name in the project -> its system folder, for links between references; and the system being written now.
CLASS_SYSTEMS = {}
current_system = ""
GENERATED_NOTE ="<!-- Generated by tools/docs/make_reference.py from the ## doc comments. Edit the comments, not this file. -->"


def main() -> int:
    wanted = sys.argv[1:]
    systems = sorted(name for name in os.listdir(SCRIPTS) if os.path.isdir(os.path.join(SCRIPTS, name)) and name not in NOT_PRODUCTION)
    if wanted:
        unknown = [name for name in wanted if name not in systems]
        if unknown:
            print("Not a system folder under assets/scripts: " + ", ".join(unknown))
            return 1
        systems = wanted
    global current_system
    all_systems = sorted(name for name in os.listdir(SCRIPTS) if os.path.isdir(os.path.join(SCRIPTS, name)) and name not in NOT_PRODUCTION)
    for system, classes in find_classes(all_systems).items():
        for _path, class_name in classes:
            if class_name:
                CLASS_SYSTEMS[class_name] = system
    classes_by_system = find_classes(systems)
    xml_folder = tempfile.mkdtemp(prefix="pb_reference_")
    try:
        if not run_doctool(xml_folder):
            return 1
        written = 0
        for system in systems:
            current_system = system
            pages = []
            for script_path, class_name in classes_by_system[system]:
                xml_path = os.path.join(xml_folder, xml_file_name(script_path, class_name))
                if not os.path.exists(xml_path):
                    # An autoload without a class_name is named after its autoload, which is its file's name here.
                    xml_path = os.path.join(xml_folder, os.path.basename(script_path)[:-3] + ".xml")
                if os.path.exists(xml_path):
                    pages.append(class_page(xml_path, script_path))
                else:
                    print("  no doc data for %s (%s)" % (class_name or "a script without class_name", script_path))
            if pages:
                write_reference(system, pages)
                written += 1
        print("Wrote %d REFERENCE.md files." % written)
    finally:
        shutil.rmtree(xml_folder, ignore_errors=True)
    return 0


# Every production script in each system: (its res:// path, its class_name or "" without one).
def find_classes(systems: list) -> dict:
    found = {}
    for system in systems:
        found[system] = []
        root = os.path.join(SCRIPTS, system)
        for folder, subfolders, files in os.walk(root):
            subfolders[:] = sorted(name for name in subfolders if name not in NOT_PRODUCTION)
            for file_name in sorted(files):
                if not file_name.endswith(".gd"):
                    continue
                full_path = os.path.join(folder, file_name)
                res_path = "res://" + os.path.relpath(full_path, PROJECT).replace(os.sep, "/")
                with open(full_path, encoding="utf-8") as script:
                    match = re.search(r"^class_name\s+(\w+)", script.read(), re.MULTILINE)
                found[system].append((res_path, match.group(1) if match else ""))
    return found


# Godot names a class_name script's file after the class, and any other script after its path, with "--" for each slash.
def xml_file_name(res_path: str, class_name: str) -> str:
    if class_name:
        return class_name + ".xml"
    return res_path[len("res://"):].replace("/", "--") + ".xml"


def run_doctool(xml_folder: str) -> bool:
    if not os.path.exists(GODOT) and shutil.which(GODOT) is None:
        print("Godot not found at %s. Set GODOT to its path." % GODOT)
        return False
    command = [GODOT, "--headless", "--path", PROJECT, "--doctool", xml_folder, "--gdscript-docs", "res://assets/scripts"]
    result = subprocess.run(command, capture_output=True, text=True, timeout=600)
    if result.returncode != 0:
        print(result.stdout[-2000:], result.stderr[-2000:])
        print("Godot's doc tool failed (exit %d)." % result.returncode)
        return False
    return True


def write_reference(system: str, pages: list) -> None:
    lines = [GENERATED_NOTE, "", "# %s reference" % system.replace("_", " ").capitalize(), ""]
    lines.append("Every class in `assets/scripts/%s/`, from its doc comments. The overview is in [README.md](README.md)." % system)
    lines.append("")
    for page in pages:
        lines.append("- [%s](#%s)" % (page[0], anchor(page[0])))
    lines.append("")
    for page in pages:
        lines.extend(page[1])
    with open(os.path.join(SCRIPTS, system, "REFERENCE.md"), "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines).rstrip() + "\n")


# One class as Markdown: returns (its title, its lines).
def class_page(xml_path: str, script_path: str) -> tuple:
    root = ElementTree.parse(xml_path).getroot()
    name = root.get("name", "")
    title = name if not name.startswith('"') else os.path.basename(script_path)
    lines = ["## %s" % title, ""]
    base = root.get("inherits", "")
    lines.append("`%s`%s" % (script_path, (", extends %s" % class_link(base)) if base else ""))
    lines.append("")
    for text in (root.findtext("brief_description"), root.findtext("description")):
        if text and text.strip():
            lines.append(markdown(text))
            lines.append("")
    add_section(lines, "Settings and properties", [
        ("`%s: %s`%s" % (m.get("name"), m.get("type", "Variant"), (" = `%s`" % m.get("default")) if m.get("default") else ""), m.text)
        for m in root.iter("member") if public(m.get("name"), m.text)])
    add_section(lines, "Signals", [
        ("`%s(%s)`" % (s.get("name"), params(s)), s.findtext("description")) for s in root.iter("signal") if public(s.get("name"), s.findtext("description"))])
    add_section(lines, "Constants", [
        ("`%s%s = %s`" % ((c.get("enum") + ".") if c.get("enum") else "", c.get("name"), c.get("value")), c.text)
        for c in root.iter("constant") if public(c.get("name"), c.text)])
    add_section(lines, "Functions", [
        ("`%s(%s) -> %s`%s" % (m.get("name"), params(m), m.find("return").get("type", "void") if m.find("return") is not None else "void",
                " *(static)*" if "static" in (m.get("qualifiers") or "") else ""), m.findtext("description"))
        for m in root.iter("method") if public(m.get("name"), m.findtext("description"))])
    return title, lines


# Underscored names are private by GDScript convention; one with a doc comment is a hook meant to be overridden, so it's kept.
def public(name: str, description: str) -> bool:
    return bool(name) and (not name.startswith("_") or bool(description and description.strip()))


def params(node) -> str:
    parts = []
    for param in sorted(node.iter("param"), key=lambda p: int(p.get("index", "0"))):
        part = "%s: %s" % (param.get("name"), param.get("type", "Variant"))
        if param.get("default") is not None:
            part += " = %s" % param.get("default")
        parts.append(part)
    return ", ".join(parts)


def add_section(lines: list, heading: str, entries: list) -> None:
    if not entries:
        return
    lines.append("### %s" % heading)
    lines.append("")
    for signature, description in entries:
        text = markdown(description or "")
        lines.append("- %s%s" % (signature, (": " + text.replace("\n", "\n  ")) if text else ""))
    lines.append("")


def anchor(title: str) -> str:
    return re.sub(r"[^a-z0-9 _-]", "", title.lower()).replace(" ", "-")


# A class name as a link: to its entry in its system's reference, or to Godot's docs for an engine class.
def class_link(name: str) -> str:
    system = CLASS_SYSTEMS.get(name)
    if system is None:
        return "[`%s`](%s)" % (name, GODOT_DOCS % name.lower())
    target = "#" + anchor(name) if system == current_system else "../%s/REFERENCE.md#%s" % (system, anchor(name))
    return "[`%s`](%s)" % (name, target)


# Godot's doc markup to Markdown.
def markdown(text: str) -> str:
    text = text.strip()
    blocks = []

    def keep_block(match):
        code = "\n".join(line.strip("\t") for line in match.group(1).strip("\n").split("\n"))
        blocks.append("```gdscript\n%s\n```" % code)
        return "\x00%d\x00" % (len(blocks) - 1)

    text = re.sub(r"\[codeblock[^\]]*\](.*?)\[/codeblock\]", keep_block, text, flags=re.DOTALL)
    # Godot puts each comment line on its own line, indented; a paragraph is a run of them.
    text = "\n".join(line.strip() for line in text.split("\n"))
    # "[br]- " starts a list item on its own line; any other [br] (a "## [br]" line between paragraphs) ends a paragraph.
    text = re.sub(r"\s*\[br\]\s*-\s+", "\n- ", text)
    text = re.sub(r"\s*\[br\]\s*", "\n\n", text)
    text = re.sub(r"\[code\](.*?)\[/code\]", r"`\1`", text)
    text = re.sub(r"\[b\](.*?)\[/b\]", r"**\1**", text)
    text = re.sub(r"\[i\](.*?)\[/i\]", r"*\1*", text)
    text = re.sub(r"\[method ([\w.]+)\]", r"`\1()`", text)
    text = re.sub(r"\[(?:member|signal|constant|enum|param) ([\w.]+)\]", r"`\1`", text)
    text = re.sub(r"\[([A-Z]\w+)\]", lambda match: class_link(match.group(1)), text)
    for index, block in enumerate(blocks):
        text = text.replace("\x00%d\x00" % index, "\n\n" + block + "\n\n")
    return re.sub(r"\n{3,}", "\n\n", text).strip()


if __name__ == "__main__":
    sys.exit(main())
