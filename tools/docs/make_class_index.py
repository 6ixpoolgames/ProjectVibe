# Written by Claude (claude-opus-5-5), 2026-11-17: writes docs/CLASS_INDEX.md, every class in the project's production code from A to Z,
# with its system, what it extends and its one-line summary, each linked to its entry in that system's REFERENCE.md (wiki spec
# section 2, phase W0). It reads the scripts directly, so it needs no Godot run.
#
# Run from the project folder, after the doc comments change:
#   python tools/docs/make_class_index.py
import os
import re

PROJECT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
SCRIPTS = os.path.join(PROJECT, "assets", "scripts")
NOT_PRODUCTION = {"tests", "debug", "samples"}
OUT = os.path.join(PROJECT, "docs", "CLASS_INDEX.md")


def main(quiet: bool = False) -> None:
    rows = []
    for system in sorted(os.listdir(SCRIPTS)):
        root = os.path.join(SCRIPTS, system)
        if not os.path.isdir(root) or system in NOT_PRODUCTION:
            continue
        for folder, subfolders, files in os.walk(root):
            subfolders[:] = [name for name in subfolders if name not in NOT_PRODUCTION]
            for name in files:
                if name.endswith(".gd"):
                    row = read_class(os.path.join(folder, name), system)
                    if row:
                        rows.append(row)
    rows.sort(key=lambda row: row[0].lower())
    lines = [
        "<!-- Generated by tools/docs/make_class_index.py from the scripts' doc comments. Edit the comments, not this file. -->",
        "",
        "# Class index",
        "",
        "Every class in the production code, A to Z. Each name links to its entry in its system's reference; the system links to its "
        "overview. %d classes." % len(rows),
        "",
        "| Class | System | Extends | What it is |",
        "|---|---|---|---|",
    ]
    for class_name, system, base, brief in rows:
        lines.append("| [%s](../assets/scripts/%s/REFERENCE.md#%s) | [%s](../assets/scripts/%s/README.md) | %s | %s |" % (
            class_name, system, class_name.lower(), system, system, base, brief.replace("|", "\\|")))
    content = "\n".join(lines) + "\n"
    # Written only when it changed: the wiki's server watches docs/, and an unchanged rewrite would start another build.
    if os.path.isfile(OUT):
        with open(OUT, encoding="utf-8") as old:
            if old.read() == content:
                return
    with open(OUT, "w", encoding="utf-8", newline="\n") as out:
        out.write(content)
    if not quiet:
        print("Wrote %s: %d classes." % (os.path.relpath(OUT, PROJECT), len(rows)))


# (class_name, system, extends, one-line summary), or None for a script without a class_name.
def read_class(path: str, system: str):
    with open(path, encoding="utf-8") as script:
        text = script.read()
    name = re.search(r"^class_name\s+(\w+)", text, re.MULTILINE)
    if not name:
        return None
    base = re.search(r"^extends\s+([\w.\"/:]+)", text, re.MULTILINE)
    # The brief is the first ## paragraph: its lines up to a blank ## line or the end of the comment. An old-style header ("## Written
    # by Claude ...: summary") gives the part after its colon.
    parts = []
    for line in text.split("\n"):
        if line.startswith("class_name") or line.startswith("extends"):
            break
        if not line.startswith("##"):
            if parts:
                break
            continue
        words = line[2:].strip()
        if words.startswith("Written by"):
            words = words.split(":", 1)[1].strip() if ":" in words else ""
        if not words or words == "[br]":
            if parts:
                break
            continue
        parts.append(words)
    brief = " ".join(parts)
    if brief:
        brief = brief[0].upper() + brief[1:]
    return name.group(1), system, base.group(1) if base else "", brief


if __name__ == "__main__":
    main()
